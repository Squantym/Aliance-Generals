// public/js/admin2/legions.js — легионы #/legions?id=lg_7
//
// Состояние экрана одно: открыт список или редактор конкретного
// легиона. В v1 оно жило в памяти вкладки, поэтому «поправь вот этому
// легиону казну» приходилось объяснять словами, а F5 посреди правки
// возвращал к списку.
//
// Отрисовку делают те же функции старой панели; им передаётся, какой
// легион открыт и как переходить.
// ===================================================================

(function () {
  function render(el, route) {
    const id = route.query.id || '';
    el.innerHTML = '<div class="a2-title">Легионы</div><div id="leg-body" class="a2-legacy"></div>';
    return Admin.renderLegions(document.getElementById('leg-body'), {
      legion: id,
      // Вход в редактор и возврат — это переходы, а не уточнения:
      // пишем в историю, чтобы «Назад» вернул к списку легионов.
      open: (next) => A2Router.setQuery({ id: next || '' }, false),
    });
  }

  A2.screens.legions = render;
})();

// ===================================================================
// public/js/admin2/tournament.js — турниры #/tournament?m=sched
//
// Единственное состояние экрана — режим («быстрый бой» или
// «расписание»). В v1 он жил в Admin._trnMode, то есть в памяти
// вкладки: ссылку на расписание было не переслать, а возврат в раздел
// всегда открывал быстрый бой, даже если работаешь с расписанием.
//
// Отрисовку делает та же функция старой панели — ей передаются режим
// и способ его сменить.
// ===================================================================

(function () {
  function render(el, route) {
    const mode = route.query.m === 'sched' ? 'sched' : 'quick';
    el.innerHTML = '<div class="a2-title">Турниры</div><div id="trn-body" class="a2-legacy"></div>';
    return Admin.renderTournament(document.getElementById('trn-body'), {
      mode,
      // Смена режима — это уточнение того же экрана, а не переход,
      // поэтому адрес заменяем: иначе «Назад» превратился бы в перебор
      // собственных переключений вместо выхода из раздела.
      setMode: (id) => A2Router.setQuery({ m: id }),
    });
  }

  A2.screens.tournament = render;
})();

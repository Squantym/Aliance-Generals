// ===================================================================
// public/js/admin2/gold.js — журнал золота #/gold?who=u_1
//
// Экран владельца: откуда у игроков золото и на что оно уходит.
// Единственный способ заметить, что кто-то раздаёт премиум-валюту
// сверх меры — поэтому «посмотри вот этого» здесь звучит часто, и
// выбранный игрок обязан быть в адресе, а не в памяти вкладки.
//
// Саму отрисовку делает старая функция: в ней разбор источников по
// группам, который писался под конкретные способы получить золото.
// Ей передаются две вещи — кто открыт и как переходить к другому.
// ===================================================================

(function () {
  function render(el, route) {
    const who = route.query.who || '';
    el.innerHTML = '<div class="a2-title">Золото</div><div id="gold-body" class="a2-legacy"></div>';
    const body = document.getElementById('gold-body');
    return Admin.renderGold(body, {
      player: who,
      // Переход не перерисовывает экран сам — он меняет адрес, а экран
      // перерисовывается уже от адреса.
      //
      // Второй параметр false — это ЗАПИСЬ в историю, а не замена.
      // Разница видна на кнопке «Назад»: смена фильтра историю засоряет
      // и должна заменяться, а вот «открыл карточку игрока» — это
      // переход, и «Назад» обязан вернуть к списку, а не выкинуть
      // из раздела на предыдущий экран панели.
      open: (id) => A2Router.setQuery({ who: id || '' }, false),
    });
  }

  A2.screens.gold = render;
})();

// ===================================================================
// public/js/admin2/tech.js — техника #/tech?p=data | p=checks
//
// В v1 «Техника» была свалкой из шести несвязанных вещей: выбор
// аккаунта, смена пароля, удаление аккаунта, почта, очереди боёв, сеть,
// мультиаккаунты, античит и база данных с копиями — одним свитком.
// Открывали её по двум совершенно разным поводам:
//   • «всё пропало» — база, копии, восстановление;
//   • «что-то странно работает» — почта, очереди, сеть, мультоводы.
// Между этими поводами нет ничего общего, кроме того, что оба редкие.
//
// Здесь они разделены на две страницы, и у каждой свой адрес. Операции
// над аккаунтом (пароль, удаление) отсюда ушли на страницу игрока —
// у «Техники» был свой отдельный поиск игрока, то есть второй способ
// выбрать не того человека.
//
// Разметку и обработчики берём из общих функций старой панели
// (_techChecksHtml / _bindTechChecks / renderDbBlock): это диагностика,
// которую правят по факту аварии, и две расходящиеся копии означали бы,
// что однажды чинишь не тот экран.
// ===================================================================

(function () {
  const PAGES = [
    ['data', '🗄 Данные и восстановление'],
    ['checks', '🩺 Проверки'],
  ];

  function render(el, route) {
    const page = route.query.p === 'checks' ? 'checks' : 'data';

    el.innerHTML = `
      <div class="a2-title">Техника</div>
      <div class="a2-card">
        <div class="a2-row">
          ${PAGES.map(([id, label]) => `<button class="btn btn-inline ${page === id ? 'btn-orange' : ''}"
            data-p="${id}">${label}</button>`).join('')}
        </div>
        <p class="a2-muted" style="margin:8px 0 0">${page === 'data'
          ? 'Копии базы, разбор «у меня всё пропало», вывоз копий за пределы сервера. Порядок действий при сбое — в файле ВОССТАНОВЛЕНИЕ.md.'
          : 'Почта, очереди боёв, сеть, мультиаккаунты, античит. Сюда идут, когда что-то работает странно.'}</p>
      </div>
      <div id="tech-body" class="a2-legacy"></div>`;

    el.querySelectorAll('[data-p]').forEach((b) => {
      b.onclick = () => A2Router.setQuery({ p: b.dataset.p });
    });

    const body = document.getElementById('tech-body');

    if (page === 'data') {
      if (!A2.can('database')) {
        body.innerHTML = `<div class="a2-card"><p class="a2-muted">Раздел базы данных доступен только
          владельцу. Это не перестраховка: отсюда откатывают коллекции и читают чужие данные целиком.</p></div>`;
        return;
      }
      // Тот же блок, что и в старой панели: копии, сверка с копией,
      // история состояния игрока, срок журнала, вывоз, снимки.
      body.innerHTML = '<div class="card" id="db-block"><div class="loading">Читаю базу…</div></div>';
      Admin.renderDbBlock();
      return;
    }

    body.innerHTML = Admin._techChecksHtml();
    Admin._bindTechChecks();
    if (!body.innerHTML.trim()) {
      body.innerHTML = `<div class="a2-card"><p class="a2-muted">Проверки закрыты правами:
        нужны «Безопасность» или права владельца.</p></div>`;
    }
  }

  A2.screens.tech = render;
})();

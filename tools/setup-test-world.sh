#!/bin/bash
# ═══════════════════════════════════════════════════════════════════
# tools/setup-test-world.sh — развернуть тестовый мир рядом с боевым
#
# Тестовый мир — ОТДЕЛЬНАЯ установка игры на том же сервере: свой
# процесс pm2, свой порт, своя папка данных, свой поддомен.
#
# Почему не «две половины внутри одной игры». Разделять миры внутри
# одной базы означало бы протащить условие «мир такой-то» через каждый
# запрос, рейтинг, бой, альянс и рассылку — сотни мест. Одно забытое —
# и тестовый игрок бьёт боевого либо попадает в общий рейтинг, причём
# заметить это можно спустя недели. У отдельных процессов разные файлы
# базы: они физически не видят друг друга, и забыть тут нечего.
#
# Запуск (один раз):
#   bash tools/setup-test-world.sh
#
# Обновление тестового мира потом — обычным деплоем в его папке:
#   cd ~/Aliance-Generals-test && bash tools/deploy.sh origin/моя-ветка
# ═══════════════════════════════════════════════════════════════════
set -euo pipefail

PROD_DIR="${PROD_DIR:-$HOME/Aliance-Generals}"
TEST_DIR="${TEST_DIR:-$HOME/Aliance-Generals-test}"
TEST_PORT="${TEST_PORT:-3001}"
TEST_NAME="${TEST_NAME:-generals-test}"
REPO="${REPO:-}"

echo "═══ Разворачиваю тестовый мир ═══"
echo "  боевой:  $PROD_DIR"
echo "  тестовый: $TEST_DIR (порт $TEST_PORT, процесс $TEST_NAME)"
echo ""

[ -d "$PROD_DIR" ] || { echo "⛔ Боевой каталог $PROD_DIR не найден"; exit 1; }

if [ -d "$TEST_DIR" ]; then
  echo "⚠ Каталог $TEST_DIR уже существует — не трогаю его."
  echo "  Если нужно начать заново: mv \"$TEST_DIR\" \"$TEST_DIR.old\""
  exit 1
fi

# Репозиторий берём у боевой установки, чтобы не спрашивать адрес.
if [ -z "$REPO" ]; then
  REPO="$(git -C "$PROD_DIR" remote get-url origin 2>/dev/null || echo '')"
fi
[ -n "$REPO" ] || { echo "⛔ Не удалось определить адрес репозитория. Задайте REPO=..."; exit 1; }

echo "[1/5] Клонирую репозиторий"
git clone "$REPO" "$TEST_DIR"
cd "$TEST_DIR"

echo "[2/5] Готовлю настройки"
# .env НЕ копируем целиком: в боевом лежат ключи почты и платежей.
# Тестовый мир, шлющий настоящие письма настоящим людям и тратящий
# лимит боевого тарифа, — это авария, а не тест.
cat > .env <<ENV
# ═══ ТЕСТОВЫЙ МИР ═══
# Отдельная установка. Боевые ключи сюда НЕ переносятся намеренно:
# письма отсюда уходить не должны, а лимит боевого тарифа — не должен
# тратиться на тесты.

PORT=$TEST_PORT
TEST_WORLD=1
TEST_WORLD_NAME=Тестовый мир

# Своя база, отдельная от боевой
DB_DRIVER=sqlite
SQLITE_DIR=./data
SQLITE_FILE=generals.db

# Почта НЕ настроена намеренно: без ключа игра подтверждает адрес сама,
# и тестировщику не нужен ящик. Аккаунты заводятся кнопкой в панели.
# SMTPBZ_API_KEY=

APP_URL=https://test.aliance-general.ru

# Второй фактор для панели. На тесте можно выключить, если он мешает,
# но лучше оставить: пусть тестовый мир ведёт себя как боевой.
# STAFF_2FA_REQUIRED=0
ENV
mkdir -p data
echo "      .env создан, боевые ключи НЕ скопированы"

echo "[3/5] Зависимости и сборка"
npm install
npm run build
[ -f dist/server.js ] || { echo "⛔ dist/server.js не собрался"; exit 1; }

echo "[4/5] Запускаю процесс"
if pm2 describe "$TEST_NAME" > /dev/null 2>&1; then
  pm2 restart "$TEST_NAME" --update-env
else
  pm2 start dist/server.js --name "$TEST_NAME" --update-env
fi
pm2 save > /dev/null 2>&1 || true

echo "[5/5] Проверяю"
sleep 4
CODE="$(curl -s -o /dev/null -w '%{http_code}' "http://localhost:${TEST_PORT}/" || true)"
if [ "$CODE" = "200" ]; then
  echo "      ✅ тестовый сервер отвечает на порту $TEST_PORT"
else
  echo "      ⚠ не ответил (код '$CODE'). Логи: pm2 logs $TEST_NAME --lines 40 --nostream"
fi

cat <<'DONE'

═══ Готово ═══

Осталось три шага, их делает человек:

1. ПОДДОМЕН. Добавьте в DNS запись A для test.aliance-general.ru на тот
   же адрес сервера, и настройте nginx (пример — в ОБНОВЛЕНИЯ-И-ТЕСТ.md).

2. ВЛАДЕЛЕЦ. В тестовом мире своя база: она пуста, прав нет ни у кого,
   а публичная регистрация закрыта. Разрываем круг из консоли:
       cd ~/Aliance-Generals-test
       node tools/test-account.js "ВашПозывной" вашпароль123
       node tools/grant-admin.js "ВашПозывной" --owner --yes

3. ТЕСТИРОВЩИКИ. Панель → «Обновление» → «Создать аккаунт».
   Логин и пароль показываются один раз — передайте их человеку.

Обновление тестового мира — кнопкой в его же панели:
    «Обновление» → «Обновить тестовый мир»
Консоль остаётся запасным путём:
    cd ~/Aliance-Generals-test && bash tools/deploy.sh origin/ваша-ветка

DONE

// ===================================================================
// src/services/testWorld.ts — признак тестового мира
//
// Тестовый мир — это ОТДЕЛЬНАЯ УСТАНОВКА игры на том же сервере: свой
// процесс, свой порт, своя папка данных, свой поддомен. Не «вторая
// половина» внутри одной базы.
//
// Почему именно так, а не флагом на игроке. Разделять миры внутри одной
// установки означало бы протащить условие «мир такой-то» через каждый
// запрос, каждый рейтинг, каждый бой, альянс и рассылку — сотни мест.
// Одно забытое место — и тестовый игрок бьёт боевого либо попадает в
// общий рейтинг. Причём заметить это можно спустя недели. Отдельная
// установка даёт то же самое бесплатно и без единого шанса на утечку:
// у процессов разные файлы базы, они физически не видят друг друга.
//
// Включается переменной TEST_WORLD=1 в .env тестовой установки.
// На боевой установке её нет, поэтому весь код ниже там выключен.
//
// Что меняет тестовый мир:
//
//  1. ЗАКРЫВАЕТ ПУБЛИЧНУЮ РЕГИСТРАЦИЮ. Аккаунты заводит владелец и
//     раздаёт тестировщикам. Иначе тестовый мир станет вторым живым,
//     со своими игроками и своими обязательствами перед ними.
//  2. ПОЗВОЛЯЕТ ЗАВЕСТИ АККАУНТ БЕЗ ПОЧТЫ. Тестировщику не нужен ящик,
//     а ждать письмо на каждый тестовый вход — потерянное время.
//  3. ПОМЕЧАЕТ СЕБЯ ВЕЗДЕ. Полоса «ТЕСТОВЫЙ МИР» в игре и в панели.
//     Перепутать окна и раздать награды не тем людям — ошибка, которая
//     случается ровно один раз и запоминается надолго.
//  4. ЗАПРЕЩАЕТ СЕБЯ ИНДЕКСИРОВАТЬ. Поисковикам тестовый мир не нужен.
// ===================================================================

const ON = String(process.env.TEST_WORLD || '') === '1';

// Название — чтобы в интерфейсе было видно, КАКОЙ это мир, если
// установок когда-нибудь станет больше двух.
const NAME = String(process.env.TEST_WORLD_NAME || 'Тестовый мир').slice(0, 40);

function isOn(): boolean { return ON; }

function view() {
  return {
    on: ON,
    name: ON ? NAME : '',
    // Почта в тестовом мире обычно не настроена — тогда игра и так
    // подтверждает адрес сама. Показываем это явно, чтобы владелец не
    // искал, почему письма не приходят.
    mailConfigured: (() => {
      try { return !!require('./email').isConfigured; } catch (e) { return false; }
    })(),
  };
}

export = { isOn, view, NAME };

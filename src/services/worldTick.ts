// ===================================================================
// src/services/worldTick.ts — фоновый «тик» мира
//
// Раз в 30 секунд: разрешаем истёкшие аукционы, стартуем назначенные
// бои, доводим ракеты, финализируем спуски в шахту, катим неделю сезона,
// пишем срез аналитики и сохраняем данные.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Раньше всё это лежало прямо в server.ts, внутри
// setInterval. Пока в тике не было условий, так было нормально. Но с
// заморозкой на время обновления в нём появилось РЕШЕНИЕ — «двигать мир
// или нет», — а решение, до которого тест может добраться только
// подождав тридцать секунд живого сервера, на практике не проверяется
// никогда. Здесь оно вызывается одной строчкой.
//
// ДВЕ ПОЛОВИНЫ ТИКА, И ЭТО ГЛАВНОЕ
//
//   ИГРОВАЯ половина двигает мир и на время обновления ЗАМИРАЕТ. Бой
//   легиона, назначенный на середину получасового окна, иначе прошёл бы
//   в закрытой игре: все его участники проиграли бы, не сделав ни
//   одного хода и даже не узнав, что война была.
//
//   ХОЗЯЙСТВЕННАЯ половина работает всегда. Сохранение данных, упаковка
//   журнала и прореживание истории к игровым срокам отношения не имеют,
//   а остановить запись на полчаса — верный способ потерять всё, что
//   сотрудник делал в закрытой игре.
//
// Сроки после открытия не «догоняют»: их сдвигает вперёд разморозка
// (src/services/timefreeze.ts). Было «через пять минут» — снова стало
// «через пять минут».
// ===================================================================
import db = require('../core/db');

let lastThin = 0;

// Игровая половина. Отдельной функцией, чтобы тест мог позвать её
// напрямую и убедиться, что при закрытой игре она не делает ничего.
function gameTick(): void {
  require('./market').tick();
  require('./legion').resolveWars();
  require('./tournaments').tick();          // авто-старт матчей и продвижение сетки
  require('./silos').resolveInFlight();     // долёт летящих ракет
  require('./seasons').rolloverIfNeeded();  // смена недели: наградить топ-3 ДО любых сбросов
  require('./mines').tickAll();             // шахты: уведомления о нападении вовремя + финализация спусков
  require('./fame').resetDailyIfNeeded();
}

// Хозяйственная половина — идёт и при закрытой игре.
function houseTick(): void {
  // Срез аналитики за сутки. Сам пропускает работу, если сегодняшний
  // день уже записан, — дёргать его каждые 30 секунд безопасно.
  require('./analytics').snapshotDaily();
  // Упаковка журнала старше недели — понемногу за раз, чтобы не занимать
  // единственный поток надолго. Когда хвост упакован, вызов не делает
  // ничего.
  db.packLogs(6);
  // Прореживание истории игроков: свежее подробно, старое обзорно.
  // Дешёвая операция, но и делать её каждые 30 секунд незачем — раз в
  // час достаточно.
  if (Date.now() - lastThin > 3600 * 1000) { lastThin = Date.now(); db.thinHistory(); }
  db.saveAll();
}

// Закрыта ли игра. Отдельно и через try: сломанный режим обслуживания не
// должен останавливать мир — не знаем, значит игра открыта.
function frozen(): boolean {
  try { return require('./maintenance').isOn(); } catch (e) { return false; }
}

// Ловушки РАЗДЕЛЬНЫЕ, и это важнее, чем кажется. Под одной общей одна
// упавшая война уносила бы с собой всю хозяйственную половину — то есть
// сохранение данных. Игра при этом продолжала бы работать, а на диск
// ничего не писалось бы до перезапуска.
function tick(): { frozen: boolean } {
  const closed = frozen();
  if (!closed) {
    try { gameTick(); } catch (e) { console.error('Ошибка игрового тика:', e); }
  }
  try { houseTick(); } catch (e) { console.error('Ошибка хозяйственного тика:', e); }
  return { frozen: closed };
}

export = { tick, gameTick, houseTick, frozen };

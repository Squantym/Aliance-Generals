// ═══════════════════════════════════════════════════════════════════
// test/_guard.js — предохранитель от стирания боевой базы
//
// Сорок с лишним тестов начинаются одинаково:
//
//     const DATA = path.join(process.cwd(), 'data');
//     if (fs.existsSync(DATA)) fs.rmSync(DATA, { recursive: true, force: true });
//
// Им нужна чистая база, и на машине разработчика это безобидно: в data/
// лежат только их же временные JSON-файлы. Запускают их из корня проекта
// — так написано и в CLAUDE.md.
//
// На сервере тот же самый запуск стёр бы БОЕВУЮ базу. Причём не только
// generals.db: rmSync рекурсивный, и вместе с ней ушли бы data/backups/
// и data/worlds/ — замороженные снимки закрытых миров, которые нигде
// больше не хранятся и не восстанавливаются ниоткуда.
//
// Отменять запуск из корня нельзя — это штатный способ. Поэтому смотрим
// не на то, ОТКУДА запускают, а на то, ЧТО лежит в data/. Настоящая
// установка узнаётся по своим следам: файл базы, папка копий, папка
// замороженных миров. Ни одного из них у теста быть не может.
//
// Подключать ПЕРВОЙ строкой, до всякого стирания:
//     require('./_guard');
// ═══════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');

(function guard() {
  const dataDir = path.join(process.cwd(), 'data');
  let found;
  try {
    if (!fs.existsSync(dataDir)) return;              // стирать нечего
    // Следы настоящей установки. Список именно перечислительный: лишняя
    // остановка теста стоит минуту, а лишнее стирание — всей базы.
    found = ['generals.db', 'worlds', 'backups', 'generals.db-wal', 'generals.db-shm']
      .find((n) => fs.existsSync(path.join(dataDir, n)));
  } catch (e) {
    return;                                          // не смогли посмотреть — не мешаем
  }
  if (!found) return;

  console.error('\n⛔ ОСТАНОВЛЕНО: в data/ лежит настоящая база.');
  console.error(`   Найдено: data/${found}`);
  console.error('');
  console.error('   Этот тест стирает data/ в ТЕКУЩЕЙ папке целиком, вместе с');
  console.error('   backups/ и worlds/. Замороженные миры не восстанавливаются.');
  console.error('');
  console.error('   Запускайте из временной папки, а не из папки установки:');
  console.error(`       cd /tmp && node ${path.join(__dirname, '<имя-теста>.js')}`);
  console.error('');
  process.exit(1);
})();

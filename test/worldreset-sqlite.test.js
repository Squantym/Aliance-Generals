// test/worldreset-sqlite.test.js — обнуление мира на СВОЕЙ базе
//
// Тот же test/worldreset.test.js, но в режиме SQLite — том самом, в
// котором работает боевой сервер.
//
// Зачем отдельный файл, а не флаг. Разница между «удалить игрока из
// памяти» и «удалить его из таблицы» в файловом режиме НЕ ВИДНА: файл
// переписывается целиком, и забытый db.dropUser проходит незамеченным.
// На своей базе строка пережила бы перезапуск, и удалённые игроки
// воскресли бы — эта ошибка в проекте уже была, отсюда когда-то взялись
// одинаковые позывные в рейтинге.
//
// Проверено намеренной поломкой: если заменить db.dropUser на delete,
// файловый прогон остаётся зелёным целиком, а этот даёт четыре красных.
// То есть без него самая опасная кнопка проекта проверялась бы не в том
// режиме, в котором она работает у игроков.
//
// Запуск: node test/worldreset-sqlite.test.js  (после npm run build)
// ═══════════════════════════════════════════════════════════════════
const path = require('path');
const { spawnSync } = require('child_process');

const r = spawnSync(process.execPath,
  [path.join(__dirname, 'worldreset.test.js'), '--sqlite'],
  { stdio: 'inherit' });
process.exit(r.status === 0 ? 0 : 1);
